#!/bin/sh
# Generates Shared/Secrets.swift (server URL, write token for uploads, read token for the
# status and "What the coach sees", share token for the charts page, optional morning
# briefing endpoint) from server/.secrets. Both files are ignored by git.
# Shared/ is compiled into both the app and the widget.
#
# Start from the template: cp server/.secrets.example server/.secrets, then fill it in.
set -eu
cd "$(dirname "$0")/.."
SECRETS=server/.secrets
[ -f "$SECRETS" ] || { echo "Missing $SECRETS: copy server/.secrets.example and fill it in." >&2; exit 1; }
value() { grep "^$1=" "$SECRETS" | head -n 1 | cut -d= -f2-; }
INGEST_TOKEN=$(value INGEST_TOKEN)
READ_TOKEN=$(value READ_TOKEN)
SHARE_TOKEN=$(value SHARE_TOKEN)
SERVER_URL=${SERVER_URL:-$(value SERVER_URL)}
# Optional morning briefing receiver (a separate service of your own, see README).
# With an empty token the app sends nothing to it and its section says so.
BRIEFING_URL=${BRIEFING_URL:-$(value BRIEFING_URL)}
BRIEFING_TOKEN=$(value BRIEFING_TOKEN)
[ -n "$SERVER_URL" ] || { echo "SERVER_URL is empty in $SECRETS." >&2; exit 1; }
BRIEFING_URL=${BRIEFING_URL:-https://briefing.invalid}
umask 077
cat > Shared/Secrets.swift <<SWIFT
// Generated by scripts/make-secrets.sh: do not commit (it is in .gitignore).
import Foundation

enum Secrets {
    static let serverURL = URL(string: "$SERVER_URL")!
    static let ingestToken = "$INGEST_TOKEN"
    static let readToken = "$READ_TOKEN"
    static let shareToken = "$SHARE_TOKEN"
    static let briefingURL = URL(string: "$BRIEFING_URL")!
    static let briefingToken = "$BRIEFING_TOKEN"
}
SWIFT
echo "Created Shared/Secrets.swift"
